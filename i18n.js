function apply(next) {
  lang = next;
  localStorage.setItem("spotter-lang", lang);
  document.documentElement.lang = lang;
  const dict = copy[lang];
  if (toggle) {
    toggle.textContent = lang === "tr" ? "EN" : "TR";
    if (dict["lang.aria"]) toggle.setAttribute("aria-label", dict["lang.aria"]);
  }
  const isPrivacy = Boolean(document.querySelector(".legal"));
  const titleKey = isPrivacy ? "privacy.title" : "doc.title";
  const descKey = isPrivacy ? "privacy.description" : "doc.description";
  if (dict[titleKey]) document.title = dict[titleKey];
  const meta = document.querySelector('meta[name="description"]');
  if (meta && dict[descKey]) meta.setAttribute("content", dict[descKey]);
  setMeta("property", "og:title", dict[titleKey]);
  setMeta("property", "og:description", dict[descKey]);
  setMeta("property", "og:locale", lang === "tr" ? "tr_TR" : "en_US");
  setMeta("name", "twitter:title", dict[titleKey]);
  setMeta("name", "twitter:description", dict[descKey]);
  updateSchema(dict, lang, isPrivacy);
  document.querySelectorAll("[data-i]").forEach((el) => {
    const key = el.getAttribute("data-i");
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i-alt]").forEach((el) => {
    const key = el.getAttribute("data-i-alt");
    if (dict[key]) el.setAttribute("alt", dict[key]);
  });
  document.querySelectorAll("[data-lang]").forEach((el) => {
    el.hidden = el.getAttribute("data-lang") !== lang;
  });
}

if (toggle) {
  toggle.addEventListener("click", () => apply(lang === "tr" ? "en" : "tr"));
}
apply(lang);
